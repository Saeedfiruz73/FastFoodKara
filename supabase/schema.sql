-- KARA cloud database foundation (Supabase / PostgreSQL)
-- Run this in Supabase Dashboard -> SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.menu_items (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null,
  description text not null default '',
  price numeric(10,3) not null check (price >= 0),
  size_label text,
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  order_type text not null check (order_type in ('Dine in','Takeaway','Delivery','Online')),
  customer_name text,
  customer_phone text,
  delivery_address text,
  notes text,
  status text not null default 'New'
    check (status in ('New','Accepted','Preparing','Ready','Completed','Cancelled')),
  payment_method text check (payment_method in ('Cash','Card','Online') or payment_method is null),
  payment_status text not null default 'Unpaid'
    check (payment_status in ('Unpaid','Pending','Paid','Refunded')),
  subtotal numeric(10,3) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(10,3) not null default 0 check (delivery_fee >= 0),
  total numeric(10,3) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  menu_item_id uuid references public.menu_items(id) on delete set null,
  item_name text not null,
  size_label text,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(10,3) not null check (unit_price >= 0),
  line_total numeric(10,3) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists orders_status_created_idx on public.orders(status, created_at desc);
create index if not exists order_items_order_id_idx on public.order_items(order_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at before update on public.orders
for each row execute function public.set_updated_at();

alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Staff POS/KDS access is authenticated. Create staff accounts in Supabase Auth.
drop policy if exists "staff read menu" on public.menu_items;
create policy "staff read menu" on public.menu_items for select to authenticated using (true);
drop policy if exists "staff manage menu" on public.menu_items;
create policy "staff manage menu" on public.menu_items for all to authenticated using (true) with check (true);

drop policy if exists "staff read orders" on public.orders;
create policy "staff read orders" on public.orders for select to authenticated using (true);
drop policy if exists "staff create orders" on public.orders;
create policy "staff create orders" on public.orders for insert to authenticated with check (true);
drop policy if exists "staff update orders" on public.orders;
create policy "staff update orders" on public.orders for update to authenticated using (true) with check (true);

drop policy if exists "staff read order items" on public.order_items;
create policy "staff read order items" on public.order_items for select to authenticated using (true);
drop policy if exists "staff add order items" on public.order_items;
create policy "staff add order items" on public.order_items for insert to authenticated with check (true);
drop policy if exists "staff update order items" on public.order_items;
create policy "staff update order items" on public.order_items for update to authenticated using (true) with check (true);

-- Enable realtime updates for the kitchen screen.
do $$
begin
  alter publication supabase_realtime add table public.orders;
exception when duplicate_object then null;
when undefined_object then null;
end $$;
